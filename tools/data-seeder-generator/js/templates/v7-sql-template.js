window.SeederTemplates = window.SeederTemplates || {};

window.SeederTemplates.SQL_V7 = function(products) {
    let sqlOutput = `-- ==========================================\n`;
    sqlOutput += `-- RAW SQL V7 EXPORT\n`;
    sqlOutput += `-- Generated by TMS Product Update Utility\n`;
    sqlOutput += `-- ==========================================\n\n`;

    const getContexts = (product) => {
        if (Array.isArray(product.useContexts) && product.useContexts.length > 0) {
            return product.useContexts;
        }
        if (product.productUse === 'fortifier') return ['additive'];
        if (product.productUse === 'modular') return ['additive', 'modular'];
        return ['feed-base'];
    };

    const creates = products.filter(p => p.action === 'create');
    const updates = products.filter(p => p.action === 'update');
    const barcodeUpdates = products.filter(p => p.action === 'barcode-update');
    const formFactorAdditions = products.filter(p => p.action === 'add-form-factor');
    const formFactorUpdates = products.filter(p => p.action === 'update-form-factor');
    const manufacturers = products.filter(p => p.action === 'add-manufacturer');
    const units = products.filter(p => p.action === 'add-unit');

    // ---------------------------------------------------------
    // 1. ADD MANUFACTURERS
    // ---------------------------------------------------------
    if (manufacturers.length > 0) {
        sqlOutput += `-- --------------------------------------------------------\n`;
        sqlOutput += `-- ADD MANUFACTURERS\n`;
        sqlOutput += `-- --------------------------------------------------------\n`;
        manufacturers.forEach((m) => {
            const name = (m.manufacturerName || '').replace(/'/g, "\\'");
            const desc = (m.manufacturerDescription || '').replace(/'/g, "\\'");
            sqlOutput += `INSERT INTO \`nutrition_product_types_manufacturer\` (\`ManufacturerName\`, \`ManufacturerDescription\`, \`ManufacturerStatus\`, \`created_at\`, \`updated_at\`) \n`;
            sqlOutput += `SELECT '${name}', '${desc}', 1, NOW(), NOW() \n`;
            sqlOutput += `WHERE NOT EXISTS (SELECT 1 FROM \`nutrition_product_types_manufacturer\` WHERE \`ManufacturerName\` = '${name}');\n\n`;
        });
    }

    // ---------------------------------------------------------
    // 2. ADD UNITS
    // ---------------------------------------------------------
    if (units.length > 0) {
        sqlOutput += `-- --------------------------------------------------------\n`;
        sqlOutput += `-- ADD UNITS\n`;
        sqlOutput += `-- --------------------------------------------------------\n`;
        units.forEach(u => {
            const name = (u.unitName || '').replace(/'/g, "\\'");
            const adt = (u.unitADT || '').replace(/'/g, "\\'");
            sqlOutput += `INSERT INTO \`units\` (\`unitName\`, \`unitADTReference\`, \`unitOrder\`, \`unitCanReceiveDonorMilk\`, \`unitHospital\`, \`unitHoursOfFeedsPrepared\`, \`unitHoursOfFeedsPreparedFormula\`, \`unitBatchVolumeBreastmilk\`, \`unitBatchVolumeFormula\`, \`unitBatchVolumeSterileWater\`, \`unitActive\`, \`created_at\`, \`updated_at\`) \n`;
            sqlOutput += `SELECT '${name}', '${adt}', ${u.unitOrder || 1}, 1, 1, ${u.bmPrepCycle || 24}, ${u.formulaPrepCycle || 24}, ${u.bmMaxVolume || 0}, ${u.formulaMaxVolume || 0}, ${u.waterMaxVolume || 0}, 1, NOW(), NOW() \n`;
            sqlOutput += `WHERE NOT EXISTS (SELECT 1 FROM \`units\` WHERE \`unitName\` = '${name}');\n\n`;
        });
    }

    // ---------------------------------------------------------
    // 3. CREATE PRODUCTS
    // ---------------------------------------------------------
    if (creates.length > 0) {
        sqlOutput += `-- --------------------------------------------------------\n`;
        sqlOutput += `-- CREATE PRODUCTS\n`;
        sqlOutput += `-- --------------------------------------------------------\n`;
        creates.forEach((p, idx) => {
            const name = (p.productName || '').replace(/'/g, "\\'");
            const sName = (p.shortName || p.productName || '').replace(/'/g, "\\'");
            const contexts = getContexts(p);
            const canBeBase = contexts.includes('feed-base') ? 1 : 0;
            const canBeFortifier = contexts.includes('additive') ? 1 : 0;
            const canBeModular = contexts.includes('modular') ? 1 : 0;
            const catId = p.categoryId || (canBeFortifier && !canBeBase ? '5' : '3');
            const hl7 = (p.hl7Reference || '').replace(/'/g, "\\'");
            const uom = (p.measurementUnit || 'ml');
            const addUnit = (p.additiveUnit || uom);
            const atomicUnits = parseFloat(p.atomicUnits) || 1;
            const decimalPlaces = p.decimalPlaces !== undefined ? (parseInt(p.decimalPlaces, 10) || 0) : (addUnit === 'g' ? 1 : 0);
            const expPrepared = canBeFortifier ? (parseFloat(p.expirationPrepared) || 48) : (parseFloat(p.expirationPrepared) || 0);
            const mainBarcode = (p.productCode || '').replace(/'/g, "\\'");
            const varPrefix = `prod${idx}`;

            sqlOutput += `-- ADD PRODUCT: ${name}\n`;
            sqlOutput += `INSERT INTO \`nutrition_product_types\` SET \n`;
            sqlOutput += `    \`formtypeName\`                   = '${name}',\n`;
            sqlOutput += `    \`formtypeShortName\`              = '${sName}',\n`;
            sqlOutput += `    \`formtypeProductBarcode\`         = '${mainBarcode}',\n`;
            sqlOutput += `    \`formtypeType\`                   = '${p.productType || 1}',\n`;
            sqlOutput += `    \`formtypeCategoryID\`             = '${catId}',\n`;
            sqlOutput += `    \`formtypeMeasurementUnit\`        = '${uom}',\n`;
            sqlOutput += `    \`formtypeIsMead\`                 = '0',\n`;
            sqlOutput += `    \`formtypeOpenExpirationDate\`     = '${p.expirationOpened || 48}',\n`;
            sqlOutput += `    \`formtypeExpirationHour\`         = '${expPrepared}',\n`;
            sqlOutput += `    \`formtypeBaseCaloricValue\`       = ${p.caloricValue || 20},\n`;
            sqlOutput += `    \`formtypeDisplacement\`           = ${p.displacement || 0},\n`;
            sqlOutput += `    \`formtypeHL7Reference\`           = '${hl7}',\n`;
            sqlOutput += `    \`formtypeSupportsDirectScanning\` = 1,\n`;
            sqlOutput += `    \`formtypeCanBeBase\`              = ${canBeBase},\n`;
            sqlOutput += `    \`formtypeCanBeFortifier\`         = ${canBeFortifier},\n`;
            sqlOutput += `    \`formtypeCanBeModular\`           = ${canBeModular},\n`;
            sqlOutput += `    \`formtypeManufacturerID\`         = '2',\n`;
            sqlOutput += `    \`formtypeActive\`                 = '1';\n\n`;

            sqlOutput += `SET @${varPrefix}ID = LAST_INSERT_ID();\n\n`;

            // Use Contexts pivot entries
            if (canBeBase) {
                sqlOutput += `INSERT INTO \`nutrition_product_types__use_contexts\` (\`formtypeID\`, \`useContextID\`) VALUES (@${varPrefix}ID, 1);\n`;
            }
            if (canBeFortifier) {
                sqlOutput += `INSERT INTO \`nutrition_product_types__use_contexts\` (\`formtypeID\`, \`useContextID\`) VALUES (@${varPrefix}ID, 2);\n`;
                sqlOutput += `INSERT INTO \`nutrition_product_types__additive_context_units\` (\`productID\`, \`measurementUnitID\`, \`atomicUnitsPerMeasurementUnit\`, \`decimalPlacesDisplayed\`) VALUES (@${varPrefix}ID, ${addUnit === 'g' ? 2 : 1}, ${atomicUnits}, ${decimalPlaces});\n`;
            }
            sqlOutput += `\n`;

            if (p.hierarchy && p.hierarchy.length > 0) {
                const innerFf = p.hierarchy[0];
                const innerFfBarcode = (innerFf.barcode || mainBarcode).replace(/'/g, "\\'");

                sqlOutput += `INSERT INTO \`nutrition_product_type_items\` SET \n`;
                sqlOutput += `    \`formtypeID\`                = @${varPrefix}ID,\n`;
                sqlOutput += `    \`formtypeProductCode\`       = '${innerFfBarcode}',\n`;
                sqlOutput += `    \`formfactortypeID\`          = ${innerFf.containerId || 1},\n`;
                sqlOutput += `    \`formtypeMeasurementUnit\`   = '${uom}',\n`;
                sqlOutput += `    \`formtypeMeasurementVolume\` = ${innerFf.volume || 100},\n`;
                sqlOutput += `    \`formtypeitemName\`          = '${name}',\n`;
                sqlOutput += `    \`isRecordProtected\`         = 1,\n`;
                sqlOutput += `    \`formtypeitemActive\`        = 1;\n\n`;

                sqlOutput += `SET @${varPrefix}ItemID = LAST_INSERT_ID();\n`;
                sqlOutput += `SET @${varPrefix}ParentID = NULL;\n\n`;

                for (let i = p.hierarchy.length - 1; i >= 0; i--) {
                    const ff = p.hierarchy[i];
                    const ffBarcode = (ff.barcode || '').replace(/'/g, "\\'");

                    sqlOutput += `INSERT INTO \`nutrition_product_type_form_factors\` SET \n`;
                    sqlOutput += `    \`formfactortypeID\`       = ${ff.containerId || 1},\n`;
                    sqlOutput += `    \`formtypeitemID\`         = @${varPrefix}ItemID,\n`;
                    sqlOutput += `    \`formfactorParentID\`     = @${varPrefix}ParentID,\n`;
                    sqlOutput += `    \`formfactorBarcode\`      = '${ffBarcode}',\n`;
                    sqlOutput += `    \`formfactorUnitQuantity\` = ${ff.quantity || 1},\n`;
                    sqlOutput += `    \`isRecordProtected\`      = 1,\n`;
                    sqlOutput += `    \`formfactorActive\`       = 1,\n`;
                    sqlOutput += `    \`created_at\`             = NOW();\n\n`;

                    sqlOutput += `SET @${varPrefix}ParentID = LAST_INSERT_ID();\n\n`;
                }

                sqlOutput += `INSERT INTO \`nutrition_product_types__applicable_form_factor_types\` (\`productTypeID\`, \`formFactorTypeID\`)\n`;
                sqlOutput += `SELECT @${varPrefix}ID, ${innerFf.containerId || 1}\n`;
                sqlOutput += `WHERE NOT EXISTS (SELECT 1 FROM \`nutrition_product_types__applicable_form_factor_types\` WHERE \`productTypeID\` = @${varPrefix}ID AND \`formFactorTypeID\` = ${innerFf.containerId || 1});\n\n`;
            }

            sqlOutput += `INSERT INTO \`nutrition_product_types_history\` SET \n`;
            sqlOutput += `    \`fthistFormulaID\`          = @${varPrefix}ID,\n`;
            sqlOutput += `    \`fthistDateTime\`           = NOW(),\n`;
            sqlOutput += `    \`fthistAction\`             = 9000,\n`;
            sqlOutput += `    \`fthistUser\`               = 1,\n`;
            sqlOutput += `    \`fthistName\`               = '${name}',\n`;
            sqlOutput += `    \`fthistOrder\`              = @${varPrefix}ID,\n`;
            sqlOutput += `    \`fthistBarcode\`            = '${mainBarcode}',\n`;
            sqlOutput += `    \`fthistLabel\`              = NULL,\n`;
            sqlOutput += `    \`fthistType\`               = '${p.productType || 1}',\n`;
            sqlOutput += `    \`fthistOpenExpirationDate\` = '${p.expirationOpened || 48}',\n`;
            sqlOutput += `    \`fhistBaseCaloricValue\`    = '${p.caloricValue || 20}',\n`;
            sqlOutput += `    \`fthistMeasurementUnit\`    = '${uom}',\n`;
            sqlOutput += `    \`fthistCategoryID\`         = '${catId}',\n`;
            sqlOutput += `    \`fthistDisplacement\`       = '${p.displacement || 0}',\n`;
            sqlOutput += `    \`fthistMead\`               = 0;\n\n`;

            sqlOutput += `-- -----------------------------------------------------------------------------\n\n`;
        });
    }

    // ---------------------------------------------------------
    // 4. UPDATE PRODUCTS
    // ---------------------------------------------------------
    if (updates.length > 0) {
        sqlOutput += `-- --------------------------------------------------------\n`;
        sqlOutput += `-- UPDATE PRODUCTS\n`;
        sqlOutput += `-- --------------------------------------------------------\n`;
        updates.forEach((p, idx) => {
            const name = (p.productName || '').replace(/'/g, "\\'");
            const varPrefix = `upd${idx}`;

            sqlOutput += `-- UPDATE PRODUCT: ${name}\n`;
            sqlOutput += `SET @${varPrefix}ID = (SELECT \`formtypeID\` FROM \`nutrition_product_types\` WHERE \`formtypeName\` = '${name}' LIMIT 1);\n\n`;

            let setClauses = [];
            if (p.updateFields && p.updateFields.includes('productName')) {
                const updatedProductName = (p.newProductName || p.productName || '').replace(/'/g, "\\'");
                setClauses.push(`\`formtypeName\` = '${updatedProductName}'`);
            }
            if (p.updateFields && p.updateFields.includes('shortName')) setClauses.push(`\`formtypeShortName\` = '${(p.shortName || '').replace(/'/g, "\\'")}'`);
            if (p.updateFields && p.updateFields.includes('hl7Reference')) setClauses.push(`\`formtypeHL7Reference\` = '${(p.hl7Reference || '').replace(/'/g, "\\'")}'`);
            if (p.updateFields && p.updateFields.includes('productType')) setClauses.push(`\`formtypeType\` = '${p.productType}'`);
            if (p.updateFields && p.updateFields.includes('categoryId')) setClauses.push(`\`formtypeCategoryID\` = '${p.categoryId}'`);
            if (p.updateFields && p.updateFields.includes('caloricValue')) {
                setClauses.push(`\`formtypeBaseCaloricValue\` = ${p.caloricValue}`);
                setClauses.push(`\`formtypeCalPerOz\` = ${p.caloricValue}`);
            }
            if (p.updateFields && p.updateFields.includes('displacement')) setClauses.push(`\`formtypeDisplacement\` = ${p.displacement}`);
            if (p.updateFields && p.updateFields.includes('expirationOpened')) setClauses.push(`\`formtypeOpenExpirationDate\` = ${p.expirationOpened}`);
            if (p.updateFields && p.updateFields.includes('expirationPrepared')) setClauses.push(`\`formtypeExpirationHour\` = ${p.expirationPrepared}`);
            if (p.updateFields && p.updateFields.includes('measurementUnit')) setClauses.push(`\`formtypeMeasurementUnit\` = '${p.measurementUnit}'`);

            let useContextSql = '';
            if (p.updateFields && (p.updateFields.includes('useContexts') || p.updateFields.includes('productUse'))) {
                const contexts = getContexts(p);
                const canBeBase = contexts.includes('feed-base') ? 1 : 0;
                const canBeFortifier = contexts.includes('additive') ? 1 : 0;
                const canBeModular = contexts.includes('modular') ? 1 : 0;
                const addUnit = (p.additiveUnit || p.measurementUnit || 'ml');
                const atomicUnits = parseFloat(p.atomicUnits) || 1;
                const decimalPlaces = p.decimalPlaces !== undefined ? (parseInt(p.decimalPlaces, 10) || 0) : (addUnit === 'g' ? 1 : 0);

                setClauses.push(`\`formtypeCanBeBase\` = ${canBeBase}`);
                setClauses.push(`\`formtypeCanBeFortifier\` = ${canBeFortifier}`);
                setClauses.push(`\`formtypeCanBeModular\` = ${canBeModular}`);

                if (canBeFortifier && p.expirationPrepared && !p.updateFields.includes('expirationPrepared')) {
                    setClauses.push(`\`formtypeExpirationHour\` = ${parseFloat(p.expirationPrepared) || 48}`);
                }

                if (canBeBase) {
                    useContextSql += `INSERT INTO \`nutrition_product_types__use_contexts\` (\`formtypeID\`, \`useContextID\`) SELECT @${varPrefix}ID, 1 WHERE NOT EXISTS (SELECT 1 FROM \`nutrition_product_types__use_contexts\` WHERE \`formtypeID\` = @${varPrefix}ID AND \`useContextID\` = 1);\n`;
                } else {
                    useContextSql += `DELETE FROM \`nutrition_product_types__use_contexts\` WHERE \`formtypeID\` = @${varPrefix}ID AND \`useContextID\` = 1;\n`;
                }

                if (canBeFortifier) {
                    useContextSql += `INSERT INTO \`nutrition_product_types__use_contexts\` (\`formtypeID\`, \`useContextID\`) SELECT @${varPrefix}ID, 2 WHERE NOT EXISTS (SELECT 1 FROM \`nutrition_product_types__use_contexts\` WHERE \`formtypeID\` = @${varPrefix}ID AND \`useContextID\` = 2);\n`;
                    useContextSql += `REPLACE INTO \`nutrition_product_types__additive_context_units\` (\`productID\`, \`measurementUnitID\`, \`atomicUnitsPerMeasurementUnit\`, \`decimalPlacesDisplayed\`) VALUES (@${varPrefix}ID, ${addUnit === 'g' ? 2 : 1}, ${atomicUnits}, ${decimalPlaces});\n`;
                } else {
                    useContextSql += `DELETE FROM \`nutrition_product_types__use_contexts\` WHERE \`formtypeID\` = @${varPrefix}ID AND \`useContextID\` = 2;\n`;
                    useContextSql += `DELETE FROM \`nutrition_product_types__additive_context_units\` WHERE \`productID\` = @${varPrefix}ID;\n`;
                }
            }

            if (p.updateFields && p.updateFields.includes('manufacturer')) {
                const mfgSearch = (p.manufacturer || '').replace(/'/g, "\\'");
                sqlOutput += `SET @${varPrefix}Mfg = COALESCE((SELECT \`ManufacturerID\` FROM \`nutrition_product_types_manufacturer\` WHERE \`ManufacturerName\` LIKE '%${mfgSearch}%' OR \`ManufacturerDescription\` LIKE '%${mfgSearch}%' LIMIT 1), 3);\n`;
                setClauses.push(`\`formtypeManufacturerID\` = @${varPrefix}Mfg`);
            }

            if (setClauses.length > 0) {
                sqlOutput += `UPDATE \`nutrition_product_types\` SET \n    `;
                sqlOutput += setClauses.join(',\n    ');
                sqlOutput += `\nWHERE \`formtypeID\` = @${varPrefix}ID;\n\n`;
            }

            if (useContextSql) {
                sqlOutput += `${useContextSql}\n`;
            }

            sqlOutput += `INSERT INTO \`nutrition_product_types_history\` SET \n`;
            sqlOutput += `    \`fthistFormulaID\`          = @${varPrefix}ID,\n`;
            sqlOutput += `    \`fthistDateTime\`           = NOW(),\n`;
            sqlOutput += `    \`fthistAction\`             = 9001,\n`;
            sqlOutput += `    \`fthistUser\`               = 1,\n`;
            sqlOutput += `    \`fthistName\`               = '${name}',\n`;
            sqlOutput += `    \`fthistOrder\`              = @${varPrefix}ID;\n\n`;
        });
    }

    // ---------------------------------------------------------
    // 5. BARCODE UPDATES (Legacy CSV Compatibility)
    // ---------------------------------------------------------
    if (barcodeUpdates.length > 0) {
        sqlOutput += `-- --------------------------------------------------------\n`;
        sqlOutput += `-- BARCODE UPDATES\n`;
        sqlOutput += `-- --------------------------------------------------------\n`;
        barcodeUpdates.forEach((p) => {
            const oldBC = (p.oldProductCode || '').replace(/'/g, "\\'");
            const newBC = (p.newProductCode || '').replace(/'/g, "\\'");

            sqlOutput += `-- UPDATE BARCODE: ${oldBC} -> ${newBC}\n`;
            sqlOutput += `UPDATE \`nutrition_product_types\` SET \`formtypeProductBarcode\` = '${newBC}' WHERE \`formtypeProductBarcode\` = '${oldBC}';\n`;
            sqlOutput += `UPDATE \`nutrition_product_type_items\` SET \`formtypeProductCode\` = '${newBC}' WHERE \`formtypeProductCode\` = '${oldBC}';\n`;
            sqlOutput += `UPDATE \`nutrition_product_type_form_factors\` SET \`formfactorBarcode\` = '${newBC}' WHERE \`formfactorBarcode\` = '${oldBC}';\n\n`;
        });
    }

    // ---------------------------------------------------------
    // 6. ADD FORM FACTORS TO EXISTING PRODUCTS
    // ---------------------------------------------------------
    if (formFactorAdditions.length > 0) {
        sqlOutput += `-- --------------------------------------------------------\n`;
        sqlOutput += `-- ADD FORM FACTORS\n`;
        sqlOutput += `-- --------------------------------------------------------\n`;
        formFactorAdditions.forEach((p, idx) => {
            const name = (p.productName || '').replace(/'/g, "\\'");
            const varPrefix = `aff${idx}`;

            sqlOutput += `-- ADD FORM FACTOR TO: ${name}\n`;
            sqlOutput += `SET @${varPrefix}ID = (SELECT \`formtypeID\` FROM \`nutrition_product_types\` WHERE \`formtypeName\` = '${name}' LIMIT 1);\n\n`;

            if (p.hierarchy && p.hierarchy.length > 0) {
                const innerFf = p.hierarchy[0];
                const itemBarcode = (p.productCode || innerFf.barcode || '').replace(/'/g, "\\'");

                sqlOutput += `INSERT INTO \`nutrition_product_type_items\` SET \n`;
                sqlOutput += `    \`formtypeID\`                = @${varPrefix}ID,\n`;
                sqlOutput += `    \`formtypeProductCode\`       = '${itemBarcode}',\n`;
                sqlOutput += `    \`formfactortypeID\`          = ${innerFf.containerId || 1},\n`;
                sqlOutput += `    \`formtypeMeasurementUnit\`   = COALESCE((SELECT \`formtypeMeasurementUnit\` FROM \`nutrition_product_types\` WHERE \`formtypeID\` = @${varPrefix}ID), 'ml'),\n`;
                sqlOutput += `    \`formtypeMeasurementVolume\` = ${innerFf.volume || 100},\n`;
                sqlOutput += `    \`formtypeitemName\`          = '${name}',\n`;
                sqlOutput += `    \`isRecordProtected\`         = 1,\n`;
                sqlOutput += `    \`formtypeitemActive\`        = 1;\n\n`;

                sqlOutput += `SET @${varPrefix}ItemID = LAST_INSERT_ID();\n`;
                sqlOutput += `SET @${varPrefix}ParentID = NULL;\n\n`;

                for (let i = p.hierarchy.length - 1; i >= 0; i--) {
                    const ff = p.hierarchy[i];
                    const ffBarcode = (ff.barcode || '').replace(/'/g, "\\'");

                    sqlOutput += `INSERT INTO \`nutrition_product_type_form_factors\` SET \n`;
                    sqlOutput += `    \`formfactortypeID\`       = ${ff.containerId || 1},\n`;
                    sqlOutput += `    \`formtypeitemID\`         = @${varPrefix}ItemID,\n`;
                    sqlOutput += `    \`formfactorParentID\`     = @${varPrefix}ParentID,\n`;
                    sqlOutput += `    \`formfactorBarcode\`      = '${ffBarcode}',\n`;
                    sqlOutput += `    \`formfactorUnitQuantity\` = ${ff.quantity || 1},\n`;
                    sqlOutput += `    \`isRecordProtected\`      = 1,\n`;
                    sqlOutput += `    \`formfactorActive\`       = 1,\n`;
                    sqlOutput += `    \`created_at\`             = NOW();\n\n`;

                    sqlOutput += `SET @${varPrefix}ParentID = LAST_INSERT_ID();\n\n`;
                }

                sqlOutput += `INSERT INTO \`nutrition_product_types__applicable_form_factor_types\` (\`productTypeID\`, \`formFactorTypeID\`)\n`;
                sqlOutput += `SELECT @${varPrefix}ID, ${innerFf.containerId || 1}\n`;
                sqlOutput += `WHERE NOT EXISTS (SELECT 1 FROM \`nutrition_product_types__applicable_form_factor_types\` WHERE \`productTypeID\` = @${varPrefix}ID AND \`formFactorTypeID\` = ${innerFf.containerId || 1});\n\n`;
            }
        });
    }

    // ---------------------------------------------------------
    // 7. UPDATE ITEMS & FORM FACTORS
    // ---------------------------------------------------------
    if (formFactorUpdates.length > 0) {
        sqlOutput += `-- --------------------------------------------------------\n`;
        sqlOutput += `-- UPDATE ITEMS & FORM FACTORS\n`;
        sqlOutput += `-- --------------------------------------------------------\n`;
        formFactorUpdates.forEach((u, idx) => {
            const varPrefix = `uff${idx}`;
            const prodName = (u.productName || '').replace(/'/g, "\\'");
            const itemCode = (u.productCode || '').replace(/'/g, "\\'");
            const lookupBc = (u.lookupBarcode || '').replace(/'/g, "\\'");
            const selectedFields = Array.isArray(u.updateItemFields) ? u.updateItemFields : [];

            sqlOutput += `-- UPDATE ITEM / FORM FACTORS (${itemCode || lookupBc || prodName})\n`;
            sqlOutput += `SET @${varPrefix}ProdID = ${prodName ? `(SELECT \`formtypeID\` FROM \`nutrition_product_types\` WHERE \`formtypeName\` = '${prodName}' LIMIT 1)` : 'NULL'};\n`;

            if (itemCode) {
                sqlOutput += `SET @${varPrefix}ItemID = (SELECT \`formtypeitemID\` FROM \`nutrition_product_type_items\` WHERE \`formtypeProductCode\` = '${itemCode}' AND (@${varPrefix}ProdID IS NULL OR \`formtypeID\` = @${varPrefix}ProdID) LIMIT 1);\n`;
            } else if (lookupBc) {
                sqlOutput += `SET @${varPrefix}ItemID = (SELECT \`formtypeitemID\` FROM \`nutrition_product_type_form_factors\` WHERE \`formfactorBarcode\` = '${lookupBc}' LIMIT 1);\n`;
            } else {
                const firstCuBc = ((u.containerUpdates || []).find(cu => cu.currentBarcode)?.currentBarcode || '').replace(/'/g, "\\'");
                sqlOutput += `SET @${varPrefix}ItemID = ${firstCuBc ? `(SELECT \`formtypeitemID\` FROM \`nutrition_product_type_form_factors\` WHERE \`formfactorBarcode\` = '${firstCuBc}' LIMIT 1)` : 'NULL'};\n`;
            }

            sqlOutput += `SET @${varPrefix}ResolvedProdID = (SELECT \`formtypeID\` FROM \`nutrition_product_type_items\` WHERE \`formtypeitemID\` = @${varPrefix}ItemID LIMIT 1);\n`;
            sqlOutput += `SET @${varPrefix}OldLeafTypeID = (SELECT \`formfactortypeID\` FROM \`nutrition_product_type_items\` WHERE \`formtypeitemID\` = @${varPrefix}ItemID LIMIT 1);\n\n`;

            const itemSetClauses = [];
            if (selectedFields.includes('newProductCode') && u.newProductCode) {
                itemSetClauses.push(`\`formtypeProductCode\` = '${u.newProductCode.replace(/'/g, "\\'")}'`);
            }
            if (selectedFields.includes('itemName') && u.itemName) {
                itemSetClauses.push(`\`formtypeitemName\` = '${u.itemName.replace(/'/g, "\\'")}'`);
            }
            if (selectedFields.includes('leafContainerType') && u.leafContainerType) {
                itemSetClauses.push(`\`formfactortypeID\` = ${parseInt(u.leafContainerType, 10) || 1}`);
            }
            if (selectedFields.includes('measurementVolume')) {
                itemSetClauses.push(`\`formtypeMeasurementVolume\` = ${parseFloat(u.measurementVolume) || 0}`);
            }
            if (selectedFields.includes('measurementUnit') && u.measurementUnit) {
                itemSetClauses.push(`\`formtypeMeasurementUnit\` = '${u.measurementUnit.replace(/'/g, "\\'")}'`);
            }
            if (selectedFields.includes('itemActive') && u.itemActive !== undefined && u.itemActive !== '') {
                itemSetClauses.push(`\`formtypeitemActive\` = ${parseInt(u.itemActive, 10) ? 1 : 0}`);
            }

            if (itemSetClauses.length > 0) {
                sqlOutput += `UPDATE \`nutrition_product_type_items\` SET \n    ${itemSetClauses.join(',\n    ')}\nWHERE \`formtypeitemID\` = @${varPrefix}ItemID;\n\n`;
            }

            sqlOutput += `SET @${varPrefix}LeafFFID = (\n`;
            sqlOutput += `    SELECT \`ff\`.\`id\` FROM \`nutrition_product_type_form_factors\` AS \`ff\`\n`;
            sqlOutput += `    WHERE \`ff\`.\`formtypeitemID\` = @${varPrefix}ItemID\n`;
            sqlOutput += `      AND NOT EXISTS (\n`;
            sqlOutput += `          SELECT 1 FROM (SELECT \`formfactorParentID\` FROM \`nutrition_product_type_form_factors\` WHERE \`formtypeitemID\` = @${varPrefix}ItemID AND \`formfactorParentID\` IS NOT NULL) AS \`p\`\n`;
            sqlOutput += `          WHERE \`p\`.\`formfactorParentID\` = \`ff\`.\`id\`\n`;
            sqlOutput += `      )\n`;
            sqlOutput += `    ORDER BY \`ff\`.\`id\` DESC LIMIT 1\n`;
            sqlOutput += `);\n\n`;

            if (selectedFields.includes('leafContainerType') && u.leafContainerType) {
                const newLeafType = parseInt(u.leafContainerType, 10) || 1;
                sqlOutput += `UPDATE \`nutrition_product_type_form_factors\` SET \`formfactortypeID\` = ${newLeafType} WHERE \`id\` = @${varPrefix}LeafFFID;\n\n`;
            }

            (Array.isArray(u.containerUpdates) ? u.containerUpdates : []).forEach((cu) => {
                const ffClauses = [];
                if (cu.newContainerType) ffClauses.push(`\`formfactortypeID\` = ${parseInt(cu.newContainerType, 10) || 1}`);
                if (cu.newBarcode) ffClauses.push(`\`formfactorBarcode\` = '${cu.newBarcode.replace(/'/g, "\\'")}'`);
                if (cu.newQuantity !== undefined && cu.newQuantity !== null && cu.newQuantity !== '') {
                    ffClauses.push(`\`formfactorUnitQuantity\` = ${parseInt(cu.newQuantity, 10) || 1}`);
                }
                if (ffClauses.length === 0) return;

                if (cu.target === 'leaf') {
                    sqlOutput += `UPDATE \`nutrition_product_type_form_factors\` SET ${ffClauses.join(', ')} WHERE \`id\` = @${varPrefix}LeafFFID;\n`;
                    if (cu.newContainerType) {
                        sqlOutput += `UPDATE \`nutrition_product_type_items\` SET \`formfactortypeID\` = ${parseInt(cu.newContainerType, 10) || 1} WHERE \`formtypeitemID\` = @${varPrefix}ItemID;\n`;
                    }
                } else if (cu.target === 'outer') {
                    if (cu.currentBarcode) {
                        const curBc = cu.currentBarcode.replace(/'/g, "\\'");
                        sqlOutput += `UPDATE \`nutrition_product_type_form_factors\` SET ${ffClauses.join(', ')} WHERE \`formtypeitemID\` = @${varPrefix}ItemID AND \`formfactorBarcode\` = '${curBc}';\n`;
                    } else {
                        sqlOutput += `UPDATE \`nutrition_product_type_form_factors\` SET ${ffClauses.join(', ')} WHERE \`formtypeitemID\` = @${varPrefix}ItemID AND \`formfactorParentID\` IS NULL;\n`;
                    }
                } else if (cu.currentBarcode) {
                    const curBc = cu.currentBarcode.replace(/'/g, "\\'");
                    sqlOutput += `UPDATE \`nutrition_product_type_form_factors\` SET ${ffClauses.join(', ')} WHERE \`formfactorBarcode\` = '${curBc}';\n`;
                }
            });

            sqlOutput += `\nSET @${varPrefix}NewLeafTypeID = (SELECT \`formfactortypeID\` FROM \`nutrition_product_type_items\` WHERE \`formtypeitemID\` = @${varPrefix}ItemID LIMIT 1);\n`;
            sqlOutput += `INSERT INTO \`nutrition_product_types__applicable_form_factor_types\` (\`productTypeID\`, \`formFactorTypeID\`)\n`;
            sqlOutput += `SELECT @${varPrefix}ResolvedProdID, @${varPrefix}NewLeafTypeID\n`;
            sqlOutput += `WHERE @${varPrefix}ResolvedProdID IS NOT NULL AND @${varPrefix}NewLeafTypeID IS NOT NULL\n`;
            sqlOutput += `  AND NOT EXISTS (SELECT 1 FROM \`nutrition_product_types__applicable_form_factor_types\` WHERE \`productTypeID\` = @${varPrefix}ResolvedProdID AND \`formFactorTypeID\` = @${varPrefix}NewLeafTypeID);\n\n`;
            sqlOutput += `DELETE FROM \`nutrition_product_types__applicable_form_factor_types\`\n`;
            sqlOutput += `WHERE \`productTypeID\` = @${varPrefix}ResolvedProdID\n`;
            sqlOutput += `  AND \`formFactorTypeID\` = @${varPrefix}OldLeafTypeID\n`;
            sqlOutput += `  AND @${varPrefix}OldLeafTypeID <> @${varPrefix}NewLeafTypeID\n`;
            sqlOutput += `  AND NOT EXISTS (SELECT 1 FROM \`nutrition_product_type_items\` WHERE \`formtypeID\` = @${varPrefix}ResolvedProdID AND \`formfactortypeID\` = @${varPrefix}OldLeafTypeID);\n\n`;
        });
    }

    return sqlOutput;
};