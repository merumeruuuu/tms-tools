window.SeederTemplates = window.SeederTemplates || {};

window.SeederTemplates.SQL_V6 = function(products) {
    let sqlOutput = `-- ==========================================\n`;
    sqlOutput += `-- LEGACY SQL EXPORT\n`;
    sqlOutput += `-- Generated by TMS Product Update Utility\n`;
    sqlOutput += `-- ==========================================\n\n`;

    const creates = products.filter(p => p.action === 'create');
    const updates = products.filter(p => p.action === 'update');
    const barcodeUpdates = products.filter(p => p.action === 'barcode-update');
    const formFactorAdditions = products.filter(p => p.action === 'add-form-factor');
    const manufacturers = products.filter(p => p.action === 'add-manufacturer');
    const units = products.filter(p => p.action === 'add-unit');

    // ---------------------------------------------------------
    // 1. ADD MANUFACTURERS
    // ---------------------------------------------------------
    if (manufacturers.length > 0) {
        sqlOutput += `-- --------------------------------------------------------\n`;
        sqlOutput += `-- ADD MANUFACTURERS\n`;
        sqlOutput += `-- --------------------------------------------------------\n`;
        manufacturers.forEach((m) => {
            const name = (m.manufacturerName || '').replace(/'/g, "\\'");
            const desc = (m.manufacturerDescription || '').replace(/'/g, "\\'");
            sqlOutput += `INSERT INTO \`nutrition_product_types_manufacturer\` SET \n`;
            sqlOutput += `    \`ManufacturerName\`        = '${name}',\n`;
            sqlOutput += `    \`ManufacturerDescription\` = '${desc}',\n`;
            sqlOutput += `    \`ManufacturerStatus\`      = 1,\n`;
            sqlOutput += `    \`created_at\`              = NOW(),\n`;
            sqlOutput += `    \`updated_at\`              = NOW();\n\n`;
        });
    }

    // ---------------------------------------------------------
    // 2. ADD UNITS
    // ---------------------------------------------------------
    if (units.length > 0) {
        sqlOutput += `-- --------------------------------------------------------\n`;
        sqlOutput += `-- ADD UNITS\n`;
        sqlOutput += `-- --------------------------------------------------------\n`;
        units.forEach(u => {
            const name = (u.unitName || '').replace(/'/g, "\\'");
            const adt = (u.unitADT || '').replace(/'/g, "\\'");
            sqlOutput += `INSERT INTO \`units\` SET \n`;
            sqlOutput += `    \`unitName\`                        = '${name}',\n`;
            sqlOutput += `    \`unitADTReference\`                = '${adt}',\n`;
            sqlOutput += `    \`unitOrder\`                       = ${u.unitOrder || 1},\n`;
            sqlOutput += `    \`unitCanReceiveDonorMilk\`         = 1,\n`;
            sqlOutput += `    \`unitHospital\`                    = 1,\n`;
            sqlOutput += `    \`unitHoursOfFeedsPrepared\`        = ${u.bmPrepCycle || 24},\n`;
            sqlOutput += `    \`unitHoursOfFeedsPreparedFormula\` = ${u.formulaPrepCycle || 24},\n`;
            sqlOutput += `    \`unitBatchVolumeBreastmilk\`       = ${u.bmMaxVolume || 0},\n`;
            sqlOutput += `    \`unitBatchVolumeFormula\`          = ${u.formulaMaxVolume || 0},\n`;
            sqlOutput += `    \`unitBatchVolumeSterileWater\`     = ${u.waterMaxVolume || 0},\n`;
            sqlOutput += `    \`unitActive\`                      = 1,\n`;
            sqlOutput += `    \`created_at\`                      = NOW(),\n`;
            sqlOutput += `    \`updated_at\`                      = NOW();\n\n`;
        });
    }

    // ---------------------------------------------------------
    // 3. CREATE PRODUCTS
    // ---------------------------------------------------------
    if (creates.length > 0) {
        sqlOutput += `-- --------------------------------------------------------\n`;
        sqlOutput += `-- CREATE PRODUCTS\n`;
        sqlOutput += `-- --------------------------------------------------------\n`;
        creates.forEach((p, idx) => {
            const name = (p.productName || '').replace(/'/g, "\\'");
            const sName = (p.shortName || p.productName || '').replace(/'/g, "\\'");
            const isFortifier = p.productUse === 'fortifier' || p.productUse === 'modular' || p.categoryId === '5';
            const catId = p.categoryId || (isFortifier ? '5' : '3');
            const hl7 = (p.hl7Reference || '').replace(/'/g, "\\'");
            const uom = (p.measurementUnit || 'mL');
            const mainBarcode = (p.productCode || '').replace(/'/g, "\\'");
            
            const varPrefix = `prod${idx}`; 

            sqlOutput += `-- ADD PRODUCT: ${name}\n`;
            sqlOutput += `INSERT INTO \`nutrition_product_types\` SET \n`;
            sqlOutput += `    \`formtypeName\`                   = '${name}',\n`;
            sqlOutput += `    \`formtypeShortName\`              = '${sName}',\n`;
            sqlOutput += `    \`formtypeProductBarcode\`         = '${mainBarcode}',\n`;
            sqlOutput += `    \`formtypeType\`                   = '${p.productType || 1}',\n`;
            sqlOutput += `    \`formtypeCategoryID\`             = '${catId}',\n`;
            sqlOutput += `    \`formtypeMeasurementUnit\`        = '${uom}',\n`;
            sqlOutput += `    \`formtypeIsMead\`                 = '0',\n`;
            sqlOutput += `    \`formtypeOpenExpirationDate\`     = '${p.expirationOpened || 48}',\n`;
            sqlOutput += `    \`formtypeBaseCaloricValue\`       = ${p.caloricValue || 20},\n`;
            sqlOutput += `    \`formtypeDisplacement\`           = ${p.displacement || 0},\n`;
            sqlOutput += `    \`formtypeHL7Reference\`           = '${hl7}',\n`;
            sqlOutput += `    \`formtypeSupportsDirectScanning\` = 1,\n`;
            sqlOutput += `    \`formtypeManufacturerID\`         = '2',\n`;
            sqlOutput += `    \`formtypeActive\`                 = '1';\n\n`;

            sqlOutput += `SET @${varPrefix}ID = LAST_INSERT_ID();\n\n`;

            if (isFortifier) {
                sqlOutput += `SET @${varPrefix}FortID = 1000 + @${varPrefix}ID;\n\n`;
                sqlOutput += `INSERT INTO \`fortification_types\` SET \n`;
                sqlOutput += `    \`forttypeID\`                               = @${varPrefix}FortID,\n`;
                sqlOutput += `    \`forttypeName\`                             = '${name}',\n`;
                sqlOutput += `    \`forttypeShortName\`                        = '${sName}',\n`;
                sqlOutput += `    \`forttypeOrder\`                            = 0,\n`;
                sqlOutput += `    \`forttypeRequiresTimePrepared\`             = 0,\n`;
                sqlOutput += `    \`forttypeRequiresFortExpiry\`               = 0,\n`;
                sqlOutput += `    \`forttypeWaterDisplacement\`                = ${p.displacement || 0},\n`;
                sqlOutput += `    \`forttypeBreastmilkDisplacement\`           = ${p.displacement || 0},\n`;
                sqlOutput += `    \`forttypeCalPerOz\`                         = ${uom === 'oz' ? p.caloricValue : 0},\n`;
                sqlOutput += `    \`forttypeCalPerGram\`                       = ${uom === 'g' ? p.caloricValue : 0},\n`;
                sqlOutput += `    \`forttypeInBMTCalculator\`                  = 1,\n`;
                sqlOutput += `    \`forttypeInFTCalculator\`                   = 1,\n`;
                sqlOutput += `    \`forttypeActive\`                           = 1,\n`;
                sqlOutput += `    \`forttypeModular\`                          = ${p.productUse === 'modular' ? 1 : 0},\n`;
                sqlOutput += `    \`forttypeModularAmountCalculatedPerVolume\` = 0,\n`;
                sqlOutput += `    \`forttypeMeasurement\`                      = '${uom}',\n`;
                sqlOutput += `    \`forttypeIsWater\`                          = 0,\n`;
                sqlOutput += `    \`forttypeExpirationHour\`                   = ${p.expirationOpened || 48},\n`;
                sqlOutput += `    \`forttypeHL7Reference\`                     = '${hl7}',\n`;
                sqlOutput += `    \`formtypeMasterID\`                         = @${varPrefix}ID,\n`;
                sqlOutput += `    \`forttypeClientHL7Reference\`               = NULL;\n\n`;
                
                sqlOutput += `INSERT INTO \`nutrition_product_types__additive_context_units\` VALUES (@${varPrefix}FortID, ${uom === 'g' ? 2 : 1}, 1, ${uom === 'g' ? 1 : 0});\n\n`;
            }

            if (p.hierarchy && p.hierarchy.length > 0) {
                const uniqueCids = [...new Set(p.hierarchy.map(h => h.containerId))].join(', ');
                sqlOutput += `INSERT INTO \`nutrition_product_types__applicable_form_factor_types\`\n`;
                sqlOutput += `SELECT @${varPrefix}ID, \`fft\`.\`id\` FROM \`nutrition_product_form_factor_types\` AS \`fft\` WHERE \`fft\`.\`id\` IN (${uniqueCids});\n\n`;
                
                let previousVarName = null;
                
                for (let i = p.hierarchy.length - 1; i >= 0; i--) {
                    const ff = p.hierarchy[i];
                    const ffBarcode = (ff.barcode || '').replace(/'/g, "\\'");
                    const currentVarName = `@${varPrefix}FF_${i}`;
                    
                    sqlOutput += `INSERT INTO \`nutrition_product_type_form_factors\` SET \n`;
                    sqlOutput += `    \`productTypeID\`          = @${varPrefix}ID,\n`;
                    sqlOutput += `    \`typeID\`                 = ${ff.containerId || 1},\n`;
                    sqlOutput += `    \`barcode\`                = '${ffBarcode}',\n`;
                    sqlOutput += `    \`containedProductVolume\` = ${ff.volume || 0};\n\n`;
                    
                    sqlOutput += `SET ${currentVarName} = (\n`;
                    sqlOutput += `    SELECT \`id\` FROM \`nutrition_product_type_form_factors\`\n`;
                    sqlOutput += `    WHERE \`productTypeID\` = @${varPrefix}ID AND \`typeID\` = ${ff.containerId || 1} AND \`barcode\` = '${ffBarcode}'\n`;
                    sqlOutput += `    ORDER BY \`id\` DESC LIMIT 1\n`;
                    sqlOutput += `);\n\n`;

                    if (previousVarName) {
                        sqlOutput += `INSERT INTO \`nutrition_product_type_form_factor_containment_relations\` SET \n`;
                        sqlOutput += `    \`formFactorID\`           = ${previousVarName},\n`;
                        sqlOutput += `    \`containedFormFactorID\`  = ${currentVarName},\n`;
                        sqlOutput += `    \`containedFormFactorQty\` = ${ff.quantity || 1};\n\n`;
                    }
                    previousVarName = currentVarName;
                }
            }

            sqlOutput += `INSERT INTO \`nutrition_product_types_history\` SET \n`;
            sqlOutput += `    \`fthistFormulaID\`          = @${varPrefix}ID,\n`;
            sqlOutput += `    \`fthistDateTime\`           = NOW(),\n`;
            sqlOutput += `    \`fthistAction\`             = 9000,\n`;
            sqlOutput += `    \`fthistUser\`               = 1,\n`;
            sqlOutput += `    \`fthistName\`               = '${name}',\n`;
            sqlOutput += `    \`fthistOrder\`              = @${varPrefix}ID,\n`;
            sqlOutput += `    \`fthistBarcode\`            = '${mainBarcode}',\n`;
            sqlOutput += `    \`fthistLabel\`              = NULL,\n`;
            sqlOutput += `    \`fthistType\`               = '${p.productType || 1}',\n`;
            sqlOutput += `    \`fthistOpenExpirationDate\` = '${p.expirationOpened || 48}',\n`;
            sqlOutput += `    \`fhistBaseCaloricValue\`    = '${p.caloricValue || 20}',\n`;
            sqlOutput += `    \`fthistMeasurementUnit\`    = '${uom}',\n`;
            sqlOutput += `    \`fthistCategoryID\`         = '${catId}',\n`;
            sqlOutput += `    \`fthistDisplacement\`       = '${p.displacement || 0}',\n`;
            sqlOutput += `    \`fthistMead\`               = 0;\n\n`;
            
            sqlOutput += `-- -----------------------------------------------------------------------------\n\n`;
        });
    }

    // ---------------------------------------------------------
    // 4. UPDATE PRODUCTS
    // ---------------------------------------------------------
    if (updates.length > 0) {
        sqlOutput += `-- --------------------------------------------------------\n`;
        sqlOutput += `-- UPDATE PRODUCTS\n`;
        sqlOutput += `-- --------------------------------------------------------\n`;
        updates.forEach((p, idx) => {
            const name = (p.productName || '').replace(/'/g, "\\'");
            const varPrefix = `upd${idx}`;
            
            sqlOutput += `-- UPDATE PRODUCT: ${name}\n`;
            sqlOutput += `SET @${varPrefix}ID = (SELECT \`formtypeID\` FROM \`nutrition_product_types\` WHERE \`formtypeName\` = '${name}' LIMIT 1);\n\n`;
            
            let setClauses = [];
            if (p.updateFields && p.updateFields.includes('productName')) {
                const updatedProductName = (p.newProductName || p.productName || '').replace(/'/g, "\\'");
                setClauses.push(`\`formtypeName\` = '${updatedProductName}'`);
            }
            if (p.updateFields && p.updateFields.includes('shortName')) setClauses.push(`\`formtypeShortName\` = '${(p.shortName || '').replace(/'/g, "\\'")}'`);
            if (p.updateFields && p.updateFields.includes('hl7Reference')) setClauses.push(`\`formtypeHL7Reference\` = '${(p.hl7Reference || '').replace(/'/g, "\\'")}'`);
            if (p.updateFields && p.updateFields.includes('productType')) setClauses.push(`\`formtypeType\` = '${p.productType}'`);
            if (p.updateFields && p.updateFields.includes('categoryId')) setClauses.push(`\`formtypeCategoryID\` = '${p.categoryId}'`);
            if (p.updateFields && p.updateFields.includes('caloricValue')) {
                setClauses.push(`\`formtypeBaseCaloricValue\` = ${p.caloricValue}`);
                setClauses.push(`\`formtypeCalPerOz\` = ${p.caloricValue}`);
            }
            if (p.updateFields && p.updateFields.includes('displacement')) setClauses.push(`\`formtypeDisplacement\` = ${p.displacement}`);
            if (p.updateFields && p.updateFields.includes('expirationOpened')) setClauses.push(`\`formtypeOpenExpirationDate\` = ${p.expirationOpened}`);
            if (p.updateFields && p.updateFields.includes('expirationPrepared')) setClauses.push(`\`formtypeExpirationHour\` = ${p.expirationPrepared}`);
            if (p.updateFields && p.updateFields.includes('measurementUnit')) setClauses.push(`\`formtypeMeasurementUnit\` = '${p.measurementUnit}'`);
            
            if (p.updateFields && p.updateFields.includes('productUse')) {
                setClauses.push(`\`formtypeCanBeBase\` = ${p.productUse === 'base' ? 1 : 0}`);
                setClauses.push(`\`formtypeCanBeFortifier\` = ${p.productUse === 'fortifier' ? 1 : 0}`);
                setClauses.push(`\`formtypeCanBeModular\` = ${p.productUse === 'modular' ? 1 : 0}`);
            }

            if (p.updateFields && p.updateFields.includes('manufacturer')) {
                const mfgSearch = (p.manufacturer || '').replace(/'/g, "\\'");
                sqlOutput += `SET @${varPrefix}Mfg = COALESCE((SELECT \`ManufacturerID\` FROM \`nutrition_product_types_manufacturer\` WHERE \`ManufacturerName\` LIKE '%${mfgSearch}%' OR \`ManufacturerDescription\` LIKE '%${mfgSearch}%' LIMIT 1), 3);\n`;
                setClauses.push(`\`formtypeManufacturerID\` = @${varPrefix}Mfg`);
            }

            if (setClauses.length > 0) {
                sqlOutput += `UPDATE \`nutrition_product_types\` SET \n    `;
                sqlOutput += setClauses.join(',\n    ');
                sqlOutput += `\nWHERE \`formtypeID\` = @${varPrefix}ID;\n\n`;
            }

            sqlOutput += `INSERT INTO \`nutrition_product_types_history\` SET \n`;
            sqlOutput += `    \`fthistFormulaID\`          = @${varPrefix}ID,\n`;
            sqlOutput += `    \`fthistDateTime\`           = NOW(),\n`;
            sqlOutput += `    \`fthistAction\`             = 9001,\n`;
            sqlOutput += `    \`fthistUser\`               = 1,\n`;
            sqlOutput += `    \`fthistName\`               = '${name}',\n`;
            sqlOutput += `    \`fthistOrder\`              = @${varPrefix}ID;\n\n`;
        });
    }

    // ---------------------------------------------------------
    // 5. BARCODE UPDATES
    // ---------------------------------------------------------
    if (barcodeUpdates.length > 0) {
        sqlOutput += `-- --------------------------------------------------------\n`;
        sqlOutput += `-- BARCODE UPDATES\n`;
        sqlOutput += `-- --------------------------------------------------------\n`;
        barcodeUpdates.forEach((p) => {
            const oldBC = (p.oldProductCode || '').replace(/'/g, "\\'");
            const newBC = (p.newProductCode || '').replace(/'/g, "\\'");
            
            sqlOutput += `-- UPDATE BARCODE: ${oldBC} -> ${newBC}\n`;
            sqlOutput += `UPDATE \`nutrition_product_types\` SET \`formtypeProductBarcode\` = '${newBC}' WHERE \`formtypeProductBarcode\` = '${oldBC}';\n`;
            sqlOutput += `UPDATE \`nutrition_product_type_form_factors\` SET \`barcode\` = '${newBC}' WHERE \`barcode\` = '${oldBC}';\n\n`;
        });
    }

    // ---------------------------------------------------------
    // 6. ADD FORM FACTORS
    // ---------------------------------------------------------
    if (formFactorAdditions.length > 0) {
        sqlOutput += `-- --------------------------------------------------------\n`;
        sqlOutput += `-- ADD FORM FACTORS\n`;
        sqlOutput += `-- --------------------------------------------------------\n`;
        formFactorAdditions.forEach((p, idx) => {
            const name = (p.productName || '').replace(/'/g, "\\'");
            const varPrefix = `aff${idx}`;
            
            sqlOutput += `-- ADD FORM FACTOR TO: ${name}\n`;
            sqlOutput += `SET @${varPrefix}ID = (SELECT \`formtypeID\` FROM \`nutrition_product_types\` WHERE \`formtypeName\` = '${name}' LIMIT 1);\n\n`;
            
            if (p.hierarchy && p.hierarchy.length > 0) {
                const uniqueCids = [...new Set(p.hierarchy.map(h => h.containerId))].join(', ');
                sqlOutput += `INSERT INTO \`nutrition_product_types__applicable_form_factor_types\` (\`productTypeID\`, \`formFactorTypeID\`)\n`;
                sqlOutput += `SELECT @${varPrefix}ID, \`fft\`.\`id\` FROM \`nutrition_product_form_factor_types\` AS \`fft\` WHERE \`fft\`.\`id\` IN (${uniqueCids})\n`;
                sqlOutput += `AND NOT EXISTS (SELECT 1 FROM \`nutrition_product_types__applicable_form_factor_types\` WHERE \`productTypeID\` = @${varPrefix}ID AND \`formFactorTypeID\` = \`fft\`.\`id\`);\n\n`;
                
                let previousVarName = null;
                for (let i = p.hierarchy.length - 1; i >= 0; i--) {
                    const ff = p.hierarchy[i];
                    const ffBarcode = (ff.barcode || '').replace(/'/g, "\\'");
                    const currentVarName = `@${varPrefix}FF_${i}`;
                    
                    sqlOutput += `INSERT INTO \`nutrition_product_type_form_factors\` (\`productTypeID\`, \`typeID\`, \`barcode\`, \`containedProductVolume\`)\n`;
                    sqlOutput += `SELECT @${varPrefix}ID, ${ff.containerId || 1}, '${ffBarcode}', ${ff.volume || 0}\n`;
                    sqlOutput += `WHERE NOT EXISTS (SELECT 1 FROM \`nutrition_product_type_form_factors\` WHERE \`productTypeID\` = @${varPrefix}ID AND \`typeID\` = ${ff.containerId || 1} AND \`barcode\` = '${ffBarcode}');\n\n`;
                    
                    sqlOutput += `SET ${currentVarName} = (\n`;
                    sqlOutput += `    SELECT \`id\` FROM \`nutrition_product_type_form_factors\`\n`;
                    sqlOutput += `    WHERE \`productTypeID\` = @${varPrefix}ID AND \`typeID\` = ${ff.containerId || 1} AND \`barcode\` = '${ffBarcode}'\n`;
                    sqlOutput += `    ORDER BY \`id\` DESC LIMIT 1\n`;
                    sqlOutput += `);\n\n`;

                    if (previousVarName) {
                        sqlOutput += `INSERT INTO \`nutrition_product_type_form_factor_containment_relations\` (\`formFactorID\`, \`containedFormFactorID\`, \`containedFormFactorQty\`)\n`;
                        sqlOutput += `SELECT ${previousVarName}, ${currentVarName}, ${ff.quantity || 1}\n`;
                        sqlOutput += `WHERE NOT EXISTS (SELECT 1 FROM \`nutrition_product_type_form_factor_containment_relations\` WHERE \`formFactorID\` = ${previousVarName} AND \`containedFormFactorID\` = ${currentVarName});\n\n`;
                    }
                    previousVarName = currentVarName;
                }
            }
        });
    }

    return sqlOutput;
};